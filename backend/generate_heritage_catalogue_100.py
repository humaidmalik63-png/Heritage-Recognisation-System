def main():
    all_sites = INDIAN_SITES + INTERNATIONAL_SITES
    print(f"Total sites created: {len(all_sites)}")
    indian_count = sum(1 for s in all_sites if s["country"] == "India")
    intl_count = sum(1 for s in all_sites if s["country"] != "India")
    print(f"Indian sites: {indian_count}, International sites: {intl_count}")
    
    # Check for uniqueness
    ids = [s["monument_id"] for s in all_sites]
    if len(ids) != len(set(ids)):
        from collections import Counter
        dupes = [k for k, v in Counter(ids).items() if v > 1]
        raise ValueError(f"Duplicate IDs detected: {dupes}")
    
    # Verify coordinate bounds
    for s in all_sites:
        lat = s["coordinates"]["lat"]
        lng = s["coordinates"]["lng"]
        assert -90.0 <= lat <= 90.0, f"Invalid latitude in {s['monument_id']}: {lat}"
        assert -180.0 <= lng <= 180.0, f"Invalid longitude in {s['monument_id']}: {lng}"
        assert len(s["monument_name"]) > 2, f"Invalid name in {s['monument_id']}"
        assert len(s["verified_description"]) > 20, f"Invalid description in {s['monument_id']}"
        assert len(s["sources"]) > 0, f"Missing sources in {s['monument_id']}"
        assert s["recognition_readiness"] in ["RECOGNITION_READY", "METADATA_ONLY", "INSUFFICIENT_REFERENCE_DATA"]
    
    catalogue_dict = {s["monument_id"]: s for s in all_sites}
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(catalogue_dict, f, indent=2, ensure_ascii=False)
        
    print(f"Successfully generated and wrote {len(catalogue_dict)} sites to {OUTPUT_FILE}")

if __name__ == "__main__":
    main()

